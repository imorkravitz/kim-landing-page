export const activePlans = (() => {
  const live = PLANS.filter((p) => p.active);
  let inheritedBase = [];
  return live.map((p) => {
    if (p.base) inheritedBase = p.base;
    return {
      ...p,
      base: inheritedBase,
      total: p.pricePerMonth * p.months,
      /** שם התוכנית שלפניה, לנוסח "כל מה שבגולד, ובנוסף" */
      inheritsFrom: null,
    };
  }).map((p, i, all) => ({ ...p, inheritsFrom: i > 0 ? all[i - 1].name : null }));
})();

